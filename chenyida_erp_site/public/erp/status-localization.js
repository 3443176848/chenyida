function visibleValue(value, emptyLabel) {
  if (value === null || value === undefined || String(value).trim() === "") return emptyLabel;
  return String(value).trim();
}

export function statusLabel(value, emptyLabel = "—") {
  const raw = visibleValue(value, emptyLabel);
  if (raw === emptyLabel) return raw;
  return STATUS_LABELS[raw.toUpperCase()] || raw;
}

export function statusPairLabel(value, separator = " / ", emptyLabel = "—") {
  const raw = visibleValue(value, emptyLabel);
  if (raw === emptyLabel) return raw;
  const labels = raw.split("/").map((part) => statusLabel(part, emptyLabel));
  return labels.filter((label, index) => index === 0 || label !== labels[index - 1]).join(separator);
}

export function roleLabel(value, emptyLabel = "—") {
  const raw = visibleValue(value, emptyLabel);
  if (raw === emptyLabel) return raw;
  return ROLE_LABELS[raw.toLowerCase()] || raw;
}
